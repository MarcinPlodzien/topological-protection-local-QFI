#!/usr/bin/env python3
"""
Regression tests for codes/ed_interacting.py.  Run:  python3 tests/test_interacting.py

 T1  independent dense Hamiltonian (Kronecker products) == bit-coded Hamiltonian
 T2  delta = 0: edge QFI == free-fermion result of codes/bdg.py at every time
 T3  delta = 0, gamma = 1: late-time plateau == (1 - h^2/J^2)^2
 T4  gamma = 1, h = 0: plateau == [1 - (delta/J)^2]^2  (free fermions in a rotated frame)
 T5  Chebyshev propagator == full diagonalization
 T6  the Trotter angles of the submitted script generate J/2 and delta/4:
     the submitted Fig. 6 numbers are reproduced only with these rescaled couplings
 T7  parity-sector Chebyshev propagator == full-space propagator
 T8  exact mapping (h, delta) -> (-h, -delta) of the edge QFI
 T9  multithreaded propagator cheb_traces_parity_fast (numba) == cheb_traces_parity, L = 10, tJ <= 20
     (needs numba; uses 2 numba threads)
T6 passes only if the rescaled couplings reproduce the submitted values within 0.07 and the intended couplings
miss them by more than 0.1 (ok &= ...); together these two conditions are the evidence for the rescaling.
Run from the tests folder or from the repository root; imports ../codes.  Runtime: see the README of the repository.
"""
import os, sys
import numpy as np
from functools import reduce
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'codes'))
import ed_interacting as ed
import bdg

sx = np.array([[0, 1], [1, 0]], complex); sy = np.array([[0, -1j], [1j, 0]]); sz = np.diag([1., -1.]).astype(complex)
def op(o, j, L):            # site j <-> bit j: site 0 is the LAST Kronecker factor
    return reduce(np.kron, [o if i == j else np.eye(2) for i in reversed(range(L))])
def H_kron(L, J, g, h, d):
    X = [op(sx, j, L) for j in range(L)]; Y = [op(sy, j, L) for j in range(L)]; Z = [op(sz, j, L) for j in range(L)]
    H = sum(-0.5 * J * ((1 + g) * X[j] @ X[j + 1] + (1 - g) * Y[j] @ Y[j + 1]) + d * Z[j] @ Z[j + 1] for j in range(L - 1))
    return H - h * sum(Z)

ok = True
def check(name, err, tol):
    global ok
    good = err < tol; ok &= good
    print(f"{'PASS' if good else 'FAIL'}  {name}: max deviation {err:.2e} (tol {tol:.0e})")

# T1 -- note: in np.kron ordering index bit 0 is up for basis state 0, so map |up> <-> bit 1
L = 6
for (g, h, d) in ((1.0, 0.3, 0.2), (0.5, 0.2, 0.4)):
    diag, off = ed.build_H(L, 1.0, g, h, d)
    Hb = off.toarray() + np.diag(diag)
    Hk = H_kron(L, 1.0, g, h, d)
    flip = np.arange(2 ** L)[::-1]                 # kron basis: index 0 = all up
    check(f"T1 Hamiltonian gamma={g} h={h} delta={d}", np.abs(Hk[np.ix_(flip, flip)] - Hb).max(), 1e-12)

# T2
L = 8; times = np.linspace(0.3, 30, 60)
for (g, h) in ((1.0, 0.4), (0.3, 0.5), (0.8, 1.8)):
    tr = ed.dense_traces(L, 1.0, g, h, 0.0, times)
    w, v = bdg.spec(bdg.Amat(L, 1.0, g, h))
    ref = []
    for t in times:
        G = bdg.Gt(w, v, t); ref.append([G[0, 0] ** 2 + G[L, 0] ** 2, G[0, L] ** 2 + G[L, L] ** 2])
    check(f"T2 free limit gamma={g} h={h}", np.abs(tr - np.array(ref)).max(), 1e-9)

# T3, T4: window averages at L = 10 (finite-size and finite-window corrections ~1e-2)
tw = np.linspace(25, 50, 251)
for h in (0.2, 0.4):
    check(f"T3 plateau (1-h^2)^2, h={h}", abs(ed.dense_traces(10, 1.0, 1.0, h, 0.0, tw)[:, 0].mean() - (1 - h * h) ** 2), 2e-2)
# at h = 0 the zero mode lives on every second site, so the edge-edge splitting is ~(delta/J)^(L/2):
# use L = 12 and an early window, before the finite-size revival sets in
te = np.linspace(5, 20, 151)
for d in (0.2, 0.4):
    check(f"T4 plateau (1-delta^2)^2, h=0, delta={d}", abs(ed.dense_traces(12, 1.0, 1.0, 0.0, d, te)[:, 0].mean() - (1 - d * d) ** 2), 2e-2)

# T5
L = 10
t, r, nrm = ed.cheb_traces(L, 1.0, 1.0, 0.2, 0.2, 40.0, dt=0.5, nsub=4)
check("T5 Chebyshev vs dense", np.abs(r - ed.dense_traces(L, 1.0, 1.0, 0.2, 0.2, t)).max(), 1e-8)
check("T5 norm conservation", abs(nrm - 1), 1e-10)

# T6 -- submitted Trotter angles: exp(-i th XX/2) with th = -J(1+g)dt/2  => coupling J/2;  th_zz = delta dt/2 => delta/4
# The submitted code used gates exp(-i theta P/2) with angles that correspond to a Hamiltonian in spin operators
# S = sigma/2, while the paper writes H with Pauli operators.  The gate exp(-i th XX/2) with th = -J(1+g)dt/2 equals
# exp(-i dt [-(J/2)(1+g)/2] XX), i.e. half the intended exchange; the ZZ gate with th = delta dt/2 gives delta/4;
# the field gate was consistent.  Below, the intended couplings (qi) and the rescaled ones (qc: J -> J/2,
# delta -> delta/4) are evaluated at L = 10 over tJ in [25, 50]; only qc reproduces the submitted L = 12 values.
pub = {(0.2, 0.0): 0.70705, (0.0, 0.8): 0.70397, (0.0, 0.4444): 0.90580}       # submitted Fig. 6 data, L = 12, gamma = 1
print("T6  label (h, delta) | intended H | H generated by submitted angles | submitted value (L=12)")
for (h, d), pv in pub.items():
    qi = ed.dense_traces(10, 1.0, 1.0, h, d, tw)[:, 0].mean()
    qc = ed.dense_traces(10, 0.5, 1.0, h, d / 4, tw)[:, 0].mean()
    print(f"     h={h} delta={d:.4f} | {qi:.4f} | {qc:.4f} | {pv:.4f}")
    check(f"T6 submitted value reproduced by rescaled couplings (h={h}, delta={d:.3f})", abs(qc - pv), 7e-2)
    ok &= abs(qi - pv) > 0.1

# T7 -- parity-sector propagator against the full-space one (generic gamma, encoding and read-out away from the edge)
_, ra, _ = ed.cheb_traces(10, 1.0, 0.7, 0.3, 0.25, 6.0, k=2, j=3); _, rb, nb = ed.cheb_traces_parity(10, 1.0, 0.7, 0.3, 0.25, 6.0, k=2, j=3)
check("T7 parity-sector Chebyshev == full-space Chebyshev", np.abs(ra - rb).max(), 1e-10)
check("T7 norm conservation", abs(nb - 1), 1e-10)

# T8 -- exact mapping (h, delta) -> (-h, -delta): same initial state, same edge QFI (reply)
for (gm8, h8, d8) in ((1.0, 0.2, 0.2), (0.5, 0.4, 0.3)):
    t8 = list(np.linspace(0, 50, 51))
    a8 = np.array(ed.dense_traces(10, 1.0, gm8, h8, d8, t8, k=0, j=0)); b8 = np.array(ed.dense_traces(10, 1.0, gm8, -h8, -d8, t8, k=0, j=0))
    check(f"T8 (h, delta) -> (-h, -delta), gamma={gm8}, h={h8}, delta={d8}", np.abs(a8 - b8).max(), 1e-12)

# T9 -- multithreaded propagator cheb_traces_parity_fast == cheb_traces_parity (generic gamma, field and interaction)
_, r9a, n9a = ed.cheb_traces_parity(10, 1.0, 0.7, 0.3, 0.25, 20.0)
_, r9b, n9b = ed.cheb_traces_parity_fast(10, 1.0, 0.7, 0.3, 0.25, 20.0, threads=2)
check("T9 numba Chebyshev == scipy Chebyshev", np.abs(r9a - r9b).max(), 1e-12)
check("T9 norm", abs(n9a - n9b), 1e-12)

print("\nALL TESTS PASSED" if ok else "\nSOME TESTS FAILED")
sys.exit(0 if ok else 1)
